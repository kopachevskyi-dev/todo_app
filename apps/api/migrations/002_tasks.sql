CREATE TABLE planner.tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL CHECK (length(btrim(title)) > 0),
  note text,
  priority text CHECK (priority IN ('high', 'medium', 'low')),
  placement text NOT NULL CHECK (placement = 'backlog' OR placement ~ '^\d{4}-\d{2}-\d{2}$'),
  position bigint GENERATED BY DEFAULT AS IDENTITY,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done', 'not_done')),
  completed_at timestamptz,
  created_at timestamptz NOT NULL,
  deleted_at timestamptz
);
